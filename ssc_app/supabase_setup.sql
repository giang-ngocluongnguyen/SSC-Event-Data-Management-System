-- PostgreSQL audit table. JSONB lets the app inspect and undo changes safely.
CREATE TABLE IF NOT EXISTS public.audit_log (
    audit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    changed_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    table_name text NOT NULL,
    record_id text,
    action text NOT NULL CHECK (action IN ('INSERT', 'UPDATE', 'DELETE')),
    operator text,
    source text NOT NULL DEFAULT 'postgres_trigger',
    before_json jsonb,
    after_json jsonb,
    undone boolean NOT NULL DEFAULT false,
    undo_audit_id bigint,
    transaction_id bigint NOT NULL DEFAULT txid_current()
);

ALTER TABLE public.audit_log ADD COLUMN IF NOT EXISTS undone boolean DEFAULT false;
ALTER TABLE public.audit_log ADD COLUMN IF NOT EXISTS undo_audit_id bigint;
ALTER TABLE public.audit_log ADD COLUMN IF NOT EXISTS transaction_id bigint DEFAULT txid_current();

-- Make an audit table imported from SQLite compatible with PostgreSQL.
DO $audit_migration$
DECLARE
    audit_id_is_identity text;
    audit_column_type text;
BEGIN
    SELECT is_identity
    INTO audit_id_is_identity
    FROM information_schema.columns
    WHERE table_schema='public' AND table_name='audit_log' AND column_name='audit_id';

    IF audit_id_is_identity = 'NO' THEN
        CREATE SEQUENCE IF NOT EXISTS public.audit_log_audit_id_seq;
        PERFORM setval(
            'public.audit_log_audit_id_seq',
            COALESCE((SELECT MAX(audit_id) FROM public.audit_log), 0) + 1,
            false
        );
        ALTER TABLE public.audit_log
            ALTER COLUMN audit_id SET DEFAULT nextval('public.audit_log_audit_id_seq');
    END IF;

    SELECT data_type INTO audit_column_type
    FROM information_schema.columns
    WHERE table_schema='public' AND table_name='audit_log' AND column_name='undone';
    IF audit_column_type IS NOT NULL AND audit_column_type <> 'boolean' THEN
        ALTER TABLE public.audit_log ALTER COLUMN undone DROP DEFAULT;
        ALTER TABLE public.audit_log ALTER COLUMN undone TYPE boolean
        USING CASE WHEN undone IS NULL THEN false
                   WHEN lower(undone::text) IN ('1', 'true', 't', 'yes', 'y') THEN true
                   ELSE false END;
        ALTER TABLE public.audit_log ALTER COLUMN undone SET DEFAULT false;
    END IF;

    SELECT data_type INTO audit_column_type
    FROM information_schema.columns
    WHERE table_schema='public' AND table_name='audit_log' AND column_name='before_json';
    IF audit_column_type IS NOT NULL AND audit_column_type <> 'jsonb' THEN
        ALTER TABLE public.audit_log ALTER COLUMN before_json TYPE jsonb
        USING NULLIF(before_json::text, '')::jsonb;
    END IF;

    SELECT data_type INTO audit_column_type
    FROM information_schema.columns
    WHERE table_schema='public' AND table_name='audit_log' AND column_name='after_json';
    IF audit_column_type IS NOT NULL AND audit_column_type <> 'jsonb' THEN
        ALTER TABLE public.audit_log ALTER COLUMN after_json TYPE jsonb
        USING NULLIF(after_json::text, '')::jsonb;
    END IF;
END
$audit_migration$;

UPDATE public.audit_log SET undone=false WHERE undone IS NULL;
