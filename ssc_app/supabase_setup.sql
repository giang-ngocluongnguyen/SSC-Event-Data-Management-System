-- Convert SQLite-style 0/1 archive columns to PostgreSQL booleans when needed.
DO $migration$
DECLARE
    table_item text;
    column_type text;
BEGIN
    FOREACH table_item IN ARRAY ARRAY['events', 'locations', 'event_types', 'participants', 'partners']
    LOOP
        SELECT data_type
        INTO column_type
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = table_item
          AND column_name = 'is_archived';

        IF column_type IS NOT NULL AND column_type <> 'boolean' THEN
            EXECUTE format(
                'ALTER TABLE public.%I ALTER COLUMN is_archived DROP DEFAULT',
                table_item
            );
            EXECUTE format(
                'ALTER TABLE public.%I ALTER COLUMN is_archived TYPE boolean '
                'USING CASE WHEN is_archived IS NULL THEN false '
                'WHEN lower(is_archived::text) IN (''1'', ''true'', ''t'', ''yes'', ''y'') '
                'THEN true ELSE false END',
                table_item
            );
            EXECUTE format(
                'ALTER TABLE public.%I ALTER COLUMN is_archived SET DEFAULT false',
                table_item
            );
        END IF;
    END LOOP;
END
$migration$;

