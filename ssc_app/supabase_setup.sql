CREATE INDEX IF NOT EXISTS idx_audit_log_table_record
    ON public.audit_log (table_name, record_id, changed_at DESC);

-- Apply last_updated consistently, including edits made outside Streamlit.
CREATE OR REPLACE FUNCTION public.ssc_set_last_updated()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
    NEW.last_updated := CURRENT_TIMESTAMP;
    RETURN NEW;
END
$function$;

-- One generic audit function; primary-key column names are trigger arguments.
CREATE OR REPLACE FUNCTION public.ssc_capture_audit()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $function$
DECLARE
    before_data jsonb;
    after_data jsonb;
    record_data jsonb;
    audit_record_id text;
    operator_name text;
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        before_data := to_jsonb(OLD);
    END IF;
    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        after_data := to_jsonb(NEW);
    END IF;

    record_data := CASE WHEN TG_OP = 'DELETE' THEN before_data ELSE after_data END;

    SELECT string_agg(record_data ->> key_name, '/' ORDER BY ordinal_position)
    INTO audit_record_id
    FROM unnest(TG_ARGV) WITH ORDINALITY AS keys(key_name, ordinal_position);

    operator_name := COALESCE(
        NULLIF(current_setting('app.operator', true), ''),
        'SSC Admin'
    );

    INSERT INTO public.audit_log (
        table_name,
        record_id,
        action,
        operator,
        source,
        before_json,
        after_json,
        transaction_id
    ) VALUES (
        TG_TABLE_NAME,
        audit_record_id,
        TG_OP,
        operator_name,
        'postgres_trigger',
        before_data,
        after_data,
        txid_current()
    );

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END
$function$;

-- Recreate application triggers idempotently.
